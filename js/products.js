const urlParams =
    new URLSearchParams(
        window.location.search
    );


const selectedBrand =
    urlParams.get("brand");


const brandToCategory = {

    colourmill: "colour-mill",

    lorann: "Lorann"

};

let currentCategory =
    selectedBrand
        ? brandToCategory[selectedBrand]
        : "all";

const container =
    document.getElementById(
        "product-container"
    );
const title = document.getElementById("products-title");

const brandNames = {
    colourmill: "Colour Mill",
    lorann: "Lorann",
    satinice: "Satin Ice",
    wilton: "Wilton",
    callebaut: "Callebaut",
    chefmaster: "Chefmaster",
    sugarflair: "Sugarflair"
};

if (selectedBrand && title) {

    title.textContent =
        (brandNames[selectedBrand] || selectedBrand)
        + " Products";

}











function displayProducts(items) {


    container.innerHTML = "";


    if (items.length === 0) {


        container.innerHTML = `
    
    <div class="no-products">
    
    <h3>
    No ingredients found
    </h3>
    
    
    <p>
    Try searching another product.
    </p>
    
    
    </div>
    
    
    `;

        return;

    }



    items.forEach(product => {


        container.innerHTML += `


<div class="product-card">


<div class="product-image-container">

<img 
src="${product.image}"
alt="${product.name}"
class="product-image"
onclick="openModal('${product.image}')">

</div>


<h3>
${product.name}
</h3>


<p>
${product.description}
</p>


<a 
class="order-btn"
href="https://wa.me/${phone}?text=Hello Cake Tools and Decor, I am interested in ${product.name}"
target="_blank">

Order Now

</a>

</div>


`;



    });


}













let currentSearch = "";



function filterProducts() {


    let filteredProducts =
        products.filter(product => {


            let matchesCategory =
                currentCategory === "all" ||
                product.category === currentCategory;

            let matchesSearch =
                product.name
                    .toLowerCase()
                    .includes(currentSearch.toLowerCase());

            return matchesCategory && matchesSearch;


        });



    displayProducts(filteredProducts);


}



document
    .querySelectorAll(".filters button")
    .forEach(button => {

        if (button.dataset.category === currentCategory) {

            button.classList.add("active");

        }

    });

document
    .querySelectorAll(".filters button")
    .forEach(button => {


        button.addEventListener(
            "click",
            () => {


                document
                    .querySelectorAll(".filters button")
                    .forEach(btn =>
                        btn.classList.remove("active")
                    );



                button.classList.add("active");



                currentCategory =
                    button.dataset.category;



                filterProducts();



            });


    });



document
    .getElementById("search-input")
    .addEventListener(
        "input",
        (event) => {


            currentSearch =
                event.target.value;


            filterProducts();


        });

const modal =
    document.getElementById(
        "image-modal"
    );


const modalImage =
    document.getElementById(
        "modal-image"
    );



function openModal(image) {


    modal.style.display = "flex";

    modalImage.src = image;


}




document
    .getElementById("close-modal")
    .onclick = function () {


        modal.style.display = "none";


    };



modal.onclick = function (event) {


    if (event.target === modal) {

        modal.style.display = "none";

    }


};
filterProducts();

